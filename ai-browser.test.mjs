function setup(LanguageModel, extras={}) {
  const ctx=vm.createContext({LanguageModel,AbortSignal,AbortController,setTimeout,clearTimeout,...extras});
  for(const file of ['ai-planner.js','ai-browser.js']) vm.runInContext(fs.readFileSync(file,'utf8'),ctx);
  return ctx;
}
